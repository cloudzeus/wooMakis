async function main() {
  let pages = 0
  for (const p of PAGES) {
    const page = await prisma.contentPage.upsert({
      where: { slug: p.slug },
      update: { kind: p.kind, published: true },
      create: { slug: p.slug, kind: p.kind, published: true, menuOrder: PAGES.indexOf(p) },
    })
    await prisma.contentPageTranslation.upsert({
      where: { pageId_locale: { pageId: page.id, locale: 'el' } },
      update: { title: p.title, body: p.body, summary: p.summary },
      create: { pageId: page.id, locale: 'el', title: p.title, body: p.body, summary: p.summary },
    })
    pages++
  }

  let faqs = 0
  for (const [i, f] of FAQ.entries()) {
    // Keyed on the Greek question, so re-running does not duplicate.
    const existing = await prisma.faqTranslation.findFirst({
      where: { locale: 'el', question: f.question },
    })
    if (existing) continue
    await prisma.faqItem.create({
      data: {
        category: f.category,
        menuOrder: i,
        translations: { create: { locale: 'el', question: f.question, answer: f.answer } },
      },
    })
    faqs++
  }

  console.log(`content: ${pages} pages, ${faqs} new FAQ entries`)
  console.log('ΠΡΟΣΟΧΗ: τα [ΑΓΚΥΛΕΣ] στο νομικό κείμενο πρέπει να συμπληρωθούν.')
}

main().finally(() => prisma.$disconnect())
